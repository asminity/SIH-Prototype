export function validateMockData(data: MockData) {
  const transactionIds = new Set(data.transactions.map((item) => item.id))
  const walletIds = new Set(data.wallets.map((item) => item.id))
  const ipIds = new Set(data.ipAddresses.map((item) => item.id))
  const entityIds = new Set(data.entities.map((item) => item.id))
  const clusterIds = new Set(data.clusters.map((item) => item.id))
  const investigationIds = new Set(data.investigations.map((item) => item.id))
  const alertIds = new Set(data.alerts.map((item) => item.id))
  const networkObservationIds = new Set(data.networkObservations.map((item) => item.id))
  const graphNodeIds = new Set(data.graphData.nodes.map((item) => item.id))

  const requireAll = (values: string[], known: Set<string>, label: string) => {
    const missing = values.find((value) => !known.has(value))
    if (missing) throw new Error(`Mock data integrity error: unknown ${label} reference: "${missing}".`)
  }
  data.transactions.forEach((transaction) => { requireAll([transaction.inputWalletId, transaction.outputWalletId], walletIds, 'wallet'); requireAll([transaction.entityId], entityIds, 'entity'); if (transaction.clusterId) requireAll([transaction.clusterId], clusterIds, 'cluster') })
  data.networkObservations.forEach((observation) => { requireAll([observation.ipAddressId], ipIds, 'IP'); if (observation.transactionId) requireAll([observation.transactionId], transactionIds, 'transaction'); if (observation.walletId) requireAll([observation.walletId], walletIds, 'wallet') })
  data.entities.forEach((entity) => { requireAll(entity.walletIds, walletIds, 'wallet'); requireAll(entity.ipAddressIds, ipIds, 'IP'); requireAll(entity.transactionIds, transactionIds, 'transaction') })
  data.clusters.forEach((cluster) => { requireAll([cluster.entityId], entityIds, 'entity'); requireAll(cluster.transactionIds, transactionIds, 'transaction'); requireAll(cluster.walletIds, walletIds, 'wallet'); requireAll(cluster.ipAddressIds, ipIds, 'IP') })
  data.alerts.forEach((alert) => { requireAll([alert.entityId], entityIds, 'entity'); requireAll([alert.clusterId], clusterIds, 'cluster'); requireAll([alert.investigationId], investigationIds, 'investigation'); requireAll(alert.transactionIds, transactionIds, 'transaction') })
  data.investigations.forEach((investigation) => { requireAll([investigation.clusterId], clusterIds, 'cluster'); requireAll([investigation.primaryAlertId], alertIds, 'alert'); requireAll(investigation.transactionIds, transactionIds, 'transaction'); requireAll(investigation.walletIds, walletIds, 'wallet'); requireAll(investigation.ipAddressIds, ipIds, 'IP') })
  data.correlations.forEach((correlation) => { requireAll([correlation.transactionId], transactionIds, 'transaction'); requireAll([correlation.networkObservationId], networkObservationIds, 'network observation'); requireAll([correlation.walletId], walletIds, 'wallet'); requireAll([correlation.ipAddressId], ipIds, 'IP') })
  data.graphData.edges.forEach((edge) => { requireAll([edge.source, edge.target], graphNodeIds, 'graph node') })
  const primaryCluster = data.clusters.find((cluster) => cluster.id === clusterId)
  if (!primaryCluster || primaryCluster.riskScore !== 91 || primaryCluster.confidence !== 0.94 || primaryCluster.severity !== 'HIGH' || primaryCluster.status !== 'NEW' || primaryCluster.transactionIds.length !== 27 || primaryCluster.walletIds.length !== 14 || primaryCluster.ipAddressIds.length < 6) throw new Error('Mock data integrity error: Cluster #42 does not match the demonstration contract.')
  const primaryGraphCounts = {
    wallet: data.graphData.nodes.filter((node) => node.type === 'WALLET').length,
    transaction: data.graphData.nodes.filter((node) => node.type === 'TRANSACTION').length,
    ip: data.graphData.nodes.filter((node) => node.type === 'IP_ADDRESS').length,
    asn: data.graphData.nodes.filter((node) => node.type === 'ASN').length,
    country: data.graphData.nodes.filter((node) => node.type === 'COUNTRY').length,
  }
  if (primaryGraphCounts.wallet < 6 || primaryGraphCounts.transaction < 5 || primaryGraphCounts.ip < 4 || primaryGraphCounts.asn < 3 || primaryGraphCounts.country < 4) throw new Error('Mock data integrity error: Investigation graph scope does not match the network contract.')
  data.riskAssessments.forEach((assessment) => { if (assessment.breakdown.reduce((total, factor) => total + factor.points, 0) !== assessment.score) throw new Error('Mock data integrity error: risk factor points do not sum to the assessment score.') })
  if (data.alerts.find((alert) => alert.id === primaryAlertId)?.status !== 'NEW') throw new Error('Mock data integrity error: ALERT-0042 must start NEW.')
}

